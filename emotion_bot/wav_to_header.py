#!/usr/bin/env python3
"""
wav_to_header.py
Re-run this script whenever you replace a WAV file to regenerate emotion_audio.h.

Usage:
    python3 wav_to_header.py

Input  : WAV files listed in ENTRIES (44100 Hz or any rate, mono/stereo)
Output : emotion_audio.h  (same folder as this script)

Dependencies:
    pip install scipy numpy
"""

import wave, numpy as np, io, os
from scipy.signal import resample_poly
from math import gcd

TARGET_RATE = 16000   # Hz — good voice quality, small flash footprint

# ---------------------------------------------------------------------------
# Edit this table to add/rename/remove sounds.
# var_name      → C symbol used in EmotionBot.ino
# wav_path      → source WAV (relative to this script's directory)
# ---------------------------------------------------------------------------
ENTRIES = [
    ("HAPPY_WAV",   "Happy.wav"),
    ("SAD_WAV",     "Sad.wav"),
    ("ANGRY_WAV",   "Angry.wav"),
    ("NEUTRAL_WAV", "Neutral.wav"),
    # ("CALM_WAV",  "Calm.wav"),    # add more here
    # ("FEAR_WAV",  "Fear.wav"),
    # ("DISGUST_WAV","Disgust.wav"),
]

COLS = 16     # hex bytes per output line


def resample_to_wav_bytes(in_path: str, target_rate: int) -> bytes:
    with wave.open(in_path, "rb") as w:
        orig_rate  = w.getframerate()
        n_channels = w.getnchannels()
        frames     = w.readframes(w.getnframes())

    samples = np.frombuffer(frames, dtype=np.int16)
    if n_channels == 2:
        samples = samples.reshape(-1, 2).mean(axis=1).astype(np.int16)

    g    = gcd(orig_rate, target_rate)
    rs   = resample_poly(samples.astype(np.float32), target_rate // g, orig_rate // g)
    rs   = np.clip(rs, -32768, 32767).astype(np.int16)

    buf = io.BytesIO()
    with wave.open(buf, "wb") as ow:
        ow.setnchannels(1)
        ow.setsampwidth(2)
        ow.setframerate(target_rate)
        ow.writeframes(rs.tobytes())
    return buf.getvalue()


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_path   = os.path.join(script_dir, "emotion_audio.h")

    total = 0
    with open(out_path, "w") as hf:
        hf.write("// emotion_audio.h — auto-generated by wav_to_header.py\n")
        hf.write(f"// Resampled to {TARGET_RATE} Hz · 16-bit · mono\n")
        hf.write("// Place this file in the same folder as EmotionBot.ino\n")
        hf.write("#pragma once\n")
        hf.write("#include <pgmspace.h>\n\n")

        for var_name, wav_file in ENTRIES:
            wav_path = os.path.join(script_dir, wav_file)
            if not os.path.exists(wav_path):
                print(f"  SKIP {wav_file} — not found")
                hf.write(f"// {wav_file} not found — {var_name} not defined\n\n")
                continue

            data = resample_to_wav_bytes(wav_path, TARGET_RATE)
            n    = len(data)
            total += n
            hf.write(f"// {wav_file}  →  {TARGET_RATE} Hz · 16-bit · mono · {n} bytes\n")
            hf.write(f"const uint8_t {var_name}[] PROGMEM = {{\n")
            for i in range(0, n, COLS):
                chunk = data[i : i + COLS]
                hf.write("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
            hf.write("};\n")
            hf.write(f"const uint32_t {var_name}_LEN = sizeof({var_name});\n\n")
            print(f"  {var_name}: {n:,} bytes  ({n / 1024:.1f} KB)")

    print(f"\nTotal audio data : {total:,} bytes  ({total / 1024:.1f} KB)")
    print(f"Header written   : {out_path}  ({os.path.getsize(out_path) // 1024} KB text)")
    print("\nRemember: set Partition Scheme → 'Huge APP (3MB No OTA)' in Arduino IDE.")


if __name__ == "__main__":
    main()
